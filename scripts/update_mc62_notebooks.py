# ── helpers ─────────────────────────────────────────────────────────
def _cell(cell_type: str, source: str) -> dict:
    """Build a minimal Jupyter cell dict."""
    # Jupyter convention: every line ends with \n except the last
    lines = source.split("\n")
    src_list = [line + "\n" for line in lines[:-1]] + [lines[-1]]
    c = {
        "cell_type": cell_type,
        "id": uuid.uuid4().hex[:8],
        "metadata": {},
        "source": src_list,
    }
    if cell_type == "code":
        c["execution_count"] = None
        c["outputs"] = []
    return c


def _find_cell(cells: list[dict], heading_prefix: str) -> int | None:
    """Find the index of the first cell whose source starts with *heading_prefix*."""
    for i, cell in enumerate(cells):
        src = "".join(cell["source"]) if isinstance(cell["source"], list) else cell["source"]
        if src.lstrip().startswith(heading_prefix):
            return i
    return None


def _find_cell_containing(cells: list[dict], needle: str) -> int | None:
    """Find the first cell whose source contains *needle*."""
    for i, cell in enumerate(cells):
        src = "".join(cell["source"]) if isinstance(cell["source"], list) else cell["source"]
        if needle in src:
            return i
    return None


