def update_notebook(spec: dict) -> None:
    nb_path = NB_BASE / spec["dir"] / "analysis.ipynb"
    with open(nb_path, encoding="utf-8") as f:
        nb = json.load(f)

    cells = nb["cells"]
    original_count = len(cells)

    # -- Check if already updated --
    if _find_cell_containing(cells, "Eddy-Current Settling Analysis") is not None:
        print(f"  {spec['dir']}: already has eddy-current sections -- skipping")
        return
    if _find_cell_containing(cells, "Higher Harmonics Overview") is not None:
        print(f"  {spec['dir']}: already has higher harmonics section -- skipping")
        return

    # -- Find insertion points --
    summary_idx = _find_cell(cells, spec["summary_heading"])
    export_idx = _find_cell(cells, spec["export_heading"])

    if summary_idx is None:
        # Fallback: search for partial match
        summary_idx = _find_cell_containing(cells, "Summary Table")
    if export_idx is None:
        export_idx = _find_cell_containing(cells, "Export to CSV")

    if summary_idx is None or export_idx is None:
        print(f"  {spec['dir']}: could not find insertion points "
              f"(summary={summary_idx}, export={export_idx}) -- skipping")
        return

    # -- Build new cells --
    higher_cells = build_higher_harmonics_cells()
    eddy_cells = build_eddy_cells(is_streaming=spec["is_streaming"])

    # -- Insert (reverse order to preserve indices) --
    # Eddy cells go before export
    for c in reversed(eddy_cells):
        cells.insert(export_idx, c)

    # Higher harmonics go before summary (which may have shifted)
    # Re-find summary since eddy cells were inserted after it
    for c in reversed(higher_cells):
        cells.insert(summary_idx, c)

    nb["cells"] = cells
    with open(nb_path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(nb, f, indent=1, ensure_ascii=False)

    n_added = len(cells) - original_count
    print(f"  {spec['dir']}: {original_count} -> {len(cells)} cells "
          f"(+{n_added} new)")


def main():
    print("Updating MC62 analysis notebooks...")
    for spec in NOTEBOOKS:
        update_notebook(spec)
    print("\nDone. New cells have empty outputs -- re-run each notebook to populate.")


if __name__ == "__main__":
    main()
